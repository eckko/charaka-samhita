    (1, 2, "अध्याय का आरम्भ"),
    (3, 3, "भरद्वाज की खोज"),
    (4, 5, "आयुर्वेद की परम्परा"),
    (6, 7, "रोगों का आना, ऋषियों का सम्मेलन"),
    (8, 14, "एकत्र हुए ऋषि"),
    (15, 19, "आरोग्य की चिन्ता, भरद्वाज का चयन"),
    (20, 23, "भरद्वाज इन्द्र के सामने"),
    (24, 29, "आयुर्वेद का ज्ञान"),
    (30, 35, "पुनर्वसु और छह शिष्य"),
    (36, 40, "देवों की स्वीकृति, ज्ञान की प्रतिष्ठा"),
    (41, 43, "आयु और आयुर्वेद"),
